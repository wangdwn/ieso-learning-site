function applyResourceFilter() {
  renderFilteredResources();
}

function getDiffLabel(diff) {
  const map = { beginner: '🟢入门', intermediate: '🟡进阶', advanced: '🔴竞赛' };
  return map[diff] || '';
}

function renderFilteredResources() {
  console.log('📚 renderFilteredResources() called');
  const container = document.getElementById('resourceBrowserResults');
  if (!container) {
    console.error('❌ Resource container NOT found!');
    return;
  }
  console.log('✅ Resource container found, resources in RESOURCES:', RESOURCES.length);

  const typeEl = document.getElementById('resFilterType');
  const catEl = document.getElementById('resFilterCategory');
  const diffEl = document.getElementById('resFilterDifficulty');
  const searchEl = document.getElementById('resFilterSearch');

  const filters = {
    type: typeEl ? typeEl.value : 'all',
    category: catEl ? catEl.value : 'all',
    difficulty: diffEl ? diffEl.value : 'all',
    search: searchEl ? searchEl.value.trim().toLowerCase() : '',
  };

  let results = [...RESOURCES];

  if (filters.type !== 'all') {
    results = results.filter(r => r.type === filters.type);
  }
  if (filters.category !== 'all') {
    results = results.filter(r => r.category === filters.category);
  }
  if (filters.difficulty !== 'all') {
    results = results.filter(r => r.diff === filters.difficulty);
  }
  if (filters.search) {
    results = results.filter(r =>
      r.title.toLowerCase().includes(filters.search) ||
      r.category.toLowerCase().includes(filters.search) ||
      r.type.toLowerCase().includes(filters.search) ||
      (r.tag || '').toLowerCase().includes(filters.search)
    );
  }

  if (results.length === 0) {
    container.innerHTML = '<div style="text-align:center;padding:40px;color:var(--gray-400);font-size:15px;">没有找到匹配的资源，试试其他筛选条件</div>';
    return;
  }

  container.innerHTML = results.map(r => {
    const diffLabel = getDiffLabel(r.diff);
    const diffClass = r.diff === 'beginner' ? 'tag-beginner' : r.diff === 'intermediate' ? 'tag-intermediate' : 'tag-advanced';
    return `
      <div class="res-browser-item fade-in">
        <div class="rbi-top">
          <h4>${r.tag || ''} ${r.title}</h4>
          <span class="diff-badge ${diffClass}">${diffLabel}</span>
        </div>
        <div class="rbi-meta">
          <span class="rbi-type">${r.type}</span>
          <span class="rbi-cat">${r.category}</span>
          ${r.url !== '#'
            ? `<a href="${r.url}" target="_blank" class="rbi-link">查看详情 →</a>`
            : '<span style="color:var(--gray-400);font-size:12px;">🔗 链接待补充</span>'}
        </div>
      </div>
    `;
  }).join('');
}

// ====== 标签云 ======
function renderTagCloud() {
  const container = document.getElementById('tagCloud');
  if (!container) return;

  const counts = {};
  RESOURCES.forEach(r => {
    counts[r.category] = (counts[r.category] || 0) + 1;
  });

  counts['🇨🇳 国内资源'] = RESOURCES.filter(r => r.tag && r.tag.includes('🇨🇳')).length;
  if (counts['🇨🇳 国内资源'] === 0) delete counts['🇨🇳 国内资源'];

  const maxCount = Math.max(...Object.values(counts));

  container.innerHTML = Object.entries(counts)
    .sort((a, b) => b[1] - a[1])
    .map(([tag, count]) => {
      const size = 0.75 + (count / maxCount) * 0.75;
      return `<span class="cloud-tag" style="font-size:${size.toFixed(2)}rem;" onclick="filterByTag('${tag}')">${tag}</span>`;
    }).join('');
}

function filterByTag(tag) {
  const catMap = { '地质学': '地质学', '气象学': '气象学', '海洋学': '海洋学', '天文学': '天文学', '综合': '综合', '实践': '实践', '🇨🇳 国内资源': '' };
  const catEl = document.getElementById('resFilterCategory');
  if (catEl && catMap[tag]) {
    catEl.value = catMap[tag];
    applyResourceFilter();
  }
  // 滚动到资源区
  document.getElementById('resources').scrollIntoView({ behavior: 'smooth' });
}

