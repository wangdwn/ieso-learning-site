function animateNumber(el, target) {
  const duration = 2000;
  const steps = 60;
  const increment = target / steps;
  let current = 0;
  let step = 0;
  const timer = setInterval(() => {
    step++;
    current = Math.min(current + increment, target);
    el.textContent = Math.round(current) + '+';
    if (step >= steps) {
      el.textContent = target + '+';
      clearInterval(timer);
    }
  }, duration / steps);
}

