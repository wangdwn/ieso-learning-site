function saveProgress(accuracy) {
  const total = parseInt(localStorage.getItem('ieso_total_answered') || '0') +
                quizState.correct + quizState.wrong;
  const prevCorrect = parseInt(localStorage.getItem('ieso_total_correct') || '0');
  const newCorrect = prevCorrect + quizState.correct;

  localStorage.setItem('ieso_total_answered', total);
  localStorage.setItem('ieso_total_correct', newCorrect);
  updateStatsDisplay();
}

function updateStatsDisplay() {
  const total = parseInt(localStorage.getItem('ieso_total_answered') || '0');
  const correct = parseInt(localStorage.getItem('ieso_total_correct') || '0');
  const acc = total > 0 ? Math.round(correct / total * 100) : 0;

  document.getElementById('totalAnswered').textContent = total;
  document.getElementById('totalAccuracy').textContent = acc + '%';
}

function resetProgress() {
  if (confirm('确定要重置所有答题记录吗？')) {
    localStorage.removeItem('ieso_total_answered');
    localStorage.removeItem('ieso_total_correct');
    updateStatsDisplay();
  }
}

