function addToWrongBook(question) {
  let wrongBook = JSON.parse(localStorage.getItem('ieso_wrong_book') || '[]');
  // 用题目内容作为唯一标识
  const exists = wrongBook.some(item => item.q === question.q);
  if (!exists) {
    // 记录错误的题，同时记下正确答案
    wrongBook.push({
      q: question.q,
      opts: question.opts,
      ans: question.ans,
      explain: question.explain,
      wrongCount: 1,
      lastWrong: Date.now(),
    });
  } else {
    wrongBook = wrongBook.map(item => {
      if (item.q === question.q) {
        return { ...item, wrongCount: item.wrongCount + 1, lastWrong: Date.now() };
      }
      return item;
    });
  }
  localStorage.setItem('ieso_wrong_book', JSON.stringify(wrongBook));
}

function getWrongBook() {
  return JSON.parse(localStorage.getItem('ieso_wrong_book') || '[]');
}

