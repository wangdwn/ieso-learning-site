function shuffleArray(arr) {
  for (let i = arr.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [arr[i], arr[j]] = [arr[j], arr[i]];
  }
  return arr;
}

function getQuestions(category, count) {
  let pool = [];
  if (category === 'all') {
    Object.values(QUESTION_BANK).forEach(qs => pool.push(...qs));
  } else {
    pool = [...QUESTION_BANK[category]];
  }
  return shuffleArray(pool).slice(0, count);
}

function startQuiz(category) {
  const count = category === 'all' ? 10 : (QUESTION_BANK[category] || []).length;
  const questions = getQuestions(category, count);

  quizState = {
    questions,
    currentIndex: 0,
    score: 0, correct: 0, wrong: 0,
    timer: null, seconds: 0,
    answered: false, category,
  };

  document.getElementById('quizSetup').style.display = 'none';
  document.getElementById('quizPlay').style.display = 'block';
  document.getElementById('quizResult').style.display = 'none';

  // 启动计时
  quizState.timer = setInterval(() => {
    quizState.seconds++;
    document.getElementById('quizTimer').textContent =
      '⏱ ' + String(Math.floor(quizState.seconds / 60)).padStart(2, '0') + ':' +
      String(quizState.seconds % 60).padStart(2, '0');
  }, 1000);

  renderQuestion();
}

function renderQuestion() {
  const state = quizState;
  const q = state.questions[state.currentIndex];
  if (!q) return finishQuiz();

  state.answered = false;
  document.getElementById('quizQNum').textContent =
    `${state.currentIndex + 1}/${state.questions.length}`;

  const catNames = { geology: '地质学', meteorology: '气象学', oceanography: '海洋学', astronomy: '天文学', all: '综合' };
  document.getElementById('quizCategory').textContent = '📚 ' + (catNames[state.category] || '');

  document.getElementById('quizProgressFill').style.width =
    ((state.currentIndex) / state.questions.length * 100) + '%';

  document.getElementById('quizQuestion').textContent = q.q;

  const labels = ['A', 'B', 'C', 'D'];
  document.getElementById('quizOptions').innerHTML = q.opts.map((opt, i) =>
    `<button class="quiz-option" data-index="${i}" onclick="selectOption(${i})">
      <span class="qopt-label">${labels[i]}</span>
      <span>${opt}</span>
    </button>`
  ).join('');

  document.getElementById('quizExplanation').style.display = 'none';
  document.getElementById('quizNextBtn').textContent =
    state.currentIndex < state.questions.length - 1 ? '下一题 →' : '查看结果 🎯';
}

function selectOption(index) {
  if (quizState.answered) return;
  quizState.answered = true;

  const q = quizState.questions[quizState.currentIndex];
  const options = document.querySelectorAll('.quiz-option');

  options.forEach((el, i) => {
    el.classList.add('disabled');
    if (i === q.ans) el.classList.add('correct');
    if (i === index && index !== q.ans) el.classList.add('wrong');
    if (i === index) el.classList.add('selected');
  });

  if (index === q.ans) {
    quizState.correct++;
  } else {
    quizState.wrong++;
    addToWrongBook(q);
  }

  // 显示解析
  const exp = document.getElementById('quizExplanation');
  exp.innerHTML = `<h5>${index === q.ans ? '✅ 正确！' : '❌ 错误'}</h5><p>${q.explain}</p>`;
  exp.style.display = 'block';

  updateStatsDisplay();
  updateWrongReviewBtn();
}

function nextQuestion() {
  quizState.currentIndex++;
  if (quizState.currentIndex >= quizState.questions.length) {
    finishQuiz();
  } else {
    renderQuestion();
  }
}

function finishQuiz() {
  clearInterval(quizState.timer);
  const total = quizState.correct + quizState.wrong;
  const accuracy = total > 0 ? Math.round(quizState.correct / total * 100) : 0;

  document.getElementById('quizPlay').style.display = 'none';
  document.getElementById('quizResult').style.display = 'block';

  document.getElementById('qrCorrect').textContent = quizState.correct;
  document.getElementById('qrWrong').textContent = quizState.wrong;
  document.getElementById('qrAccuracy').textContent = accuracy + '%';

  // 模拟考试显示倒计时结束提示
  if (quizState.isMockExam && quizState.seconds >= quizState.timeLimit) {
    document.getElementById('qrTime').textContent = '⏰ 时间到！';
  } else {
    const timeStr = String(Math.floor(quizState.seconds / 60)).padStart(2, '0') + ':' +
                    String(quizState.seconds % 60).padStart(2, '0');
    document.getElementById('qrTime').textContent = timeStr;
  }

  const fill = document.getElementById('qrScoreFill');
  fill.style.width = accuracy + '%';
  fill.style.background = accuracy >= 80 ? 'linear-gradient(90deg,#059669,#10B981)' :
                          accuracy >= 50 ? 'linear-gradient(90deg,#D97706,#F59E0B)' :
                          'linear-gradient(90deg,#DC2626,#EF4444)';

  const icon = document.getElementById('qrIcon');
  const title = document.getElementById('qrTitle');
  const timeup = quizState.isMockExam && quizState.seconds >= quizState.timeLimit;
  if (timeup) {
    icon.textContent = '⏰';
    title.textContent = '时间到！' + (accuracy >= 50 ? ' 已完成 ' + total + ' 题' : '');
  } else if (accuracy >= 80) { icon.textContent = '🏆'; title.textContent = '太强了！IESO 奖牌在望！'; }
  else if (accuracy >= 50) { icon.textContent = '👍'; title.textContent = '不错，继续加油！'; }
  else { icon.textContent = '💪'; title.textContent = '再接再厉，多练几次就好！'; }

  // 模拟考试和错题复习不计入普通进度统计
  if (!quizState.isMockExam && !quizState.isWrongReview) {
    saveProgress(accuracy);
  }
  // 清除标志
  quizState.isMockExam = false;
  quizState.isWrongReview = false;
}

function backToMenu() {
  clearInterval(quizState.timer);
  quizState.isMockExam = false;
  document.getElementById('quizPlay').style.display = 'none';
  document.getElementById('quizResult').style.display = 'none';
  document.getElementById('quizSetup').style.display = 'block';
  const timerEl = document.getElementById('quizTimer');
  timerEl.classList.remove('timer-warning');
}

function restartQuiz() {
  if (quizState.isWrongReview) {
    reviewAllWrongQuestions();
  } else if (quizState.isMockExam) {
    startMockExam();
  } else {
    startQuiz(quizState.category);
  }
}

