function toggleLike(postId) {
  const post = communityState.posts.find(p => p.id === postId);
  if (!post) return;
  if (post.likedByUser) {
    post.likes--;
    post.likedByUser = false;
  } else {
    post.likes++;
    post.likedByUser = true;
  }
  saveCommunityPosts();
  renderCommunityPosts();
}

